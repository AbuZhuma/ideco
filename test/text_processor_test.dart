import 'package:flutter_test/flutter_test.dart';
import 'package:voice_notes/models/settings.dart';
import 'package:voice_notes/services/text_processor.dart';

void main() {
  final p = TextProcessor(DictationSettings());

  test('первая буква заглавная, пустой контекст', () {
    expect(p.append('', 'привет мир'), 'Привет мир');
  });

  test('команды пунктуации', () {
    expect(
      p.append('', 'привет запятая как дела вопросительный знак'),
      'Привет, как дела?',
    );
    expect(p.append('', 'это важно восклицательный знак'), 'Это важно!');
    expect(
      p.append('', 'список двоеточие хлеб запятая молоко точка'),
      'Список: хлеб, молоко.',
    );
  });

  test('точка зрения не превращается в знак', () {
    expect(
      p.append('', 'с моей точки зрения это верно точка'),
      'С моей точки зрения это верно.',
    );
    expect(p.append('', 'точка зрения автора'), 'Точка зрения автора');
  });

  test('заглавная после точки внутри сегмента', () {
    expect(p.append('', 'первое точка второе точка'), 'Первое. Второе.');
  });

  test('новая строка и абзац', () {
    expect(p.append('', 'раз новая строка два абзац три'), 'Раз\nДва\n\nТри');
  });

  test('склейка с контекстом: после точки — пробел и заглавная', () {
    expect(p.append('Первое.', 'второе'), 'Первое. Второе');
  });

  test('склейка после запятой — строчная', () {
    expect(p.append('Раз,', 'два'), 'Раз, два');
  });

  test('автоточка между фразами после паузы', () {
    expect(
      p.append('Первая фраза', 'вторая фраза', afterPause: true),
      'Первая фраза. Вторая фраза',
    );
    expect(
      p.append('Первая фраза', 'вторая фраза'),
      'Первая фраза вторая фраза',
    );
  });

  test('автоточка выключена', () {
    final q = TextProcessor(DictationSettings(autoPeriod: false));
    expect(q.append('Первая', 'вторая', afterPause: true), 'Первая вторая');
  });

  test('сегмент, начинающийся со знака, прижимается', () {
    expect(p.append('Привет', 'запятая мир'), 'Привет, мир');
  });

  test('контекст заканчивается переводом строки', () {
    expect(p.append('Заголовок\n', 'текст'), 'Заголовок\nТекст');
  });

  test('удалить последнее слово', () {
    expect(p.append('Привет мир', 'удалить последнее слово'), 'Привет');
    expect(
      p.append('', 'привет мир удали последнее слово друг'),
      'Привет друг',
    );
    expect(
      p.append('Список: хлеб.', 'убери последнее слово молоко'),
      'Список: молоко',
    );
  });

  test('скобки и кавычки', () {
    expect(
      p.append('', 'он сказал открыть кавычки привет закрыть кавычки и ушёл'),
      'Он сказал «привет» и ушёл',
    );
    expect(p.append('', 'см открыть скобку ниже закрыть скобку'), 'См (ниже)');
  });

  test('тире', () {
    expect(p.append('', 'москва тире столица'), 'Москва — столица');
  });

  test('с большой буквы', () {
    expect(
      p.append('', 'мы поехали в с большой буквы париж'),
      'Мы поехали в Париж',
    );
  });

  test('команды выключены', () {
    final q = TextProcessor(DictationSettings(voiceCommands: false));
    expect(q.append('', 'привет точка'), 'Привет точка');
  });

  test('уже расставленная пунктуация не дублируется', () {
    expect(p.append('', 'Привет, как дела?'), 'Привет, как дела?');
    expect(
      p.append('Привет.', 'Как дела?', afterPause: true),
      'Привет. Как дела?',
    );
  });

  test('пустой сегмент не меняет контекст', () {
    expect(p.append('Текст', '   '), 'Текст');
  });
}
